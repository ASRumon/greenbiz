/**
 * Seed generator.
 *
 * Emits `seed/seed.sql` from institutions.json and plans.json, which
 * `npm run seed` then feeds to `wrangler d1 execute`. Generating SQL (instead of
 * opening a database connection) means the same seed works for a local
 * Miniflare database and a remote D1 database with no code changes and no
 * credentials in this script.
 *
 * Idempotent: `INSERT OR REPLACE` on a stable primary key, so running it twice
 * updates the catalogue rather than duplicating it.
 *
 * Usage:  npm run seed          (local D1)
 *         npm run seed:remote   (remote D1)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

interface InstitutionSeed {
	id: string;
	name: string;
	institutionType: string;
	website: string | null;
	description: string | null;
	contactPhone: string | null;
	isActive: boolean;
}

interface PlanSeed {
	id: string;
	institutionId: string;
	planName: string;
	serviceType: string;
	description: string | null;
	minAmountMinor: number | null;
	maxAmountMinor: number | null;
	interestRateMin: number | null;
	interestRateMax: number | null;
	durationMonths: number | null;
	eligibilityCriteria: Record<string, unknown> | null;
	feesDetails: Record<string, unknown> | null;
	sourceUrl: string | null;
	lastVerifiedAt: number | null;
	isActive: boolean;
}

const institutions = JSON.parse(
	readFileSync(join(here, "institutions.json"), "utf8"),
) as InstitutionSeed[];

const plans = JSON.parse(readFileSync(join(here, "plans.json"), "utf8")) as PlanSeed[];

/** Renders a JS value as a SQLite literal. */
function sqlLiteral(value: unknown): string {
	if (value === null || value === undefined) return "NULL";
	if (typeof value === "number") {
		if (!Number.isFinite(value)) throw new Error(`Non-finite number in seed data: ${value}`);
		return String(value);
	}
	if (typeof value === "boolean") return value ? "1" : "0";
	if (typeof value === "object") return sqlLiteral(JSON.stringify(value));
	// Escape single quotes; the seed data is trusted, but a stray apostrophe in
	// a plan description must not break the generated SQL.
	return `'${String(value).replace(/'/g, "''")}'`;
}

const lines: string[] = [
	"-- Generated by seed/seed.ts - do not edit by hand.",
	"-- Source of truth: seed/institutions.json and seed/plans.json",
	"",
	"-- Catalogue source: the SME Bank Loans comparison table supplied on",
	"-- 2026-10-18. last_verified_at marks that date. Amounts are minor units;",
	"-- EMI figures shown by the app are estimates from the stated rate, amount",
	"-- and tenor, not quotes from the bank.",
	"",
	"DELETE FROM financial_service_plans;",
	"DELETE FROM financial_institutions;",
	"",
];

for (const institution of institutions) {
	lines.push(
		`INSERT OR REPLACE INTO financial_institutions (id, name, institution_type, website, description, contact_phone, is_active, created_at) VALUES (${[
			sqlLiteral(institution.id),
			sqlLiteral(institution.name),
			sqlLiteral(institution.institutionType),
			sqlLiteral(institution.website),
			sqlLiteral(institution.description),
			sqlLiteral(institution.contactPhone),
			sqlLiteral(institution.isActive),
			"CAST(strftime('%s','now') AS INTEGER) * 1000",
		].join(", ")});`,
	);
}

lines.push("");

for (const plan of plans) {
	lines.push(
		`INSERT OR REPLACE INTO financial_service_plans (id, institution_id, plan_name, service_type, description, min_amount_minor, max_amount_minor, interest_rate_min, interest_rate_max, duration_months, eligibility_criteria, fees_details, source_url, last_verified_at, is_active, created_at) VALUES (${[
			sqlLiteral(plan.id),
			sqlLiteral(plan.institutionId),
			sqlLiteral(plan.planName),
			sqlLiteral(plan.serviceType),
			sqlLiteral(plan.description),
			sqlLiteral(plan.minAmountMinor),
			sqlLiteral(plan.maxAmountMinor),
			sqlLiteral(plan.interestRateMin),
			sqlLiteral(plan.interestRateMax),
			sqlLiteral(plan.durationMonths),
			sqlLiteral(plan.eligibilityCriteria),
			sqlLiteral(plan.feesDetails),
			sqlLiteral(plan.sourceUrl),
			sqlLiteral(plan.lastVerifiedAt),
			sqlLiteral(plan.isActive),
			"CAST(strftime('%s','now') AS INTEGER) * 1000",
		].join(", ")});`,
	);
}

const outputPath = join(here, "seed.sql");
writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");

console.log(
	`Wrote ${outputPath}\n  ${institutions.length} institutions, ${plans.length} plans`,
);
